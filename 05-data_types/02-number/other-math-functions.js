// Math.random(): Returns a random number from 0 to 1 (not including 1).
alert(`Random: ${Math.random()}`); // 0.1234567894322
alert(`Random: ${Math.random()}`); // 0.5435252343232
alert(`Random: ${Math.random()}`); // ... (any random numbers)

// Math.max(a, b, c...) and Math.min(a, b, c...): Returns the greatest and
// smallest from the arbitrary number of arguments:
alert(`Max from 3, 5, -10, 0, 1: ${Math.max(3, 5, -10, 0, 1)}`); // 5
alert(`Min from 1, 2: ${Math.min(1, 2)}`); // 1

// Math.pow(n, power): Returns n raised to the given power.
alert(`2**10: ${Math.pow(2, 10)}`); // 2 in power 10 = 1024
