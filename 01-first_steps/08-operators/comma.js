// Comma
// The comma operator allows us to evaluate several expressions, dividing them
// with a comma ,. Each of them is evaluated but only the result of the last
// one is returned.
let a = (1 + 2, 3 + 4);

alert(a); // 7 (the result of 3 + 4)

